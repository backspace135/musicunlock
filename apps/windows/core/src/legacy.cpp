Bytes decode_legacy(ByteSpan input, std::string_view ext, ByteSpan kgm_mask) {
    if (ext == "uc") {
        Bytes audio(input.begin(), input.end());
        for (auto& byte : audio) byte ^= 0xa3;
        return audio;
    }
    if (ext == "tm0" || ext == "tm3") return Bytes(input.begin(), input.end());
    if (ext == "tm2" || ext == "tm6") {
        if (input.size() < 32 ||
            !std::all_of(input.begin() + 8, input.begin() + 12, [](std::uint8_t b) { return b >= 0x20 && b <= 0x7e; })) {
            fail_invalid("TM 文件未包含有效的 MP4 音频头部");
        }
        Bytes audio = {0, 0, 0, 0x20, 0x66, 0x74, 0x79, 0x70};
        audio.insert(audio.end(), input.begin() + 8, input.end());
        return audio;
    }
    if (ext == "kwm") return kuwo(input);
    if (ext == "xm") return xiami(input);
    if (ext == "kgm" || ext == "kgma" || ext == "vpr") return kugou(input, ext == "vpr", kgm_mask);
    fail_unsupported("暂不支持 ." + std::string(ext));
}

