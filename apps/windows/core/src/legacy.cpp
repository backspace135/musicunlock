Bytes kuwo(ByteSpan input) {
    if (input.size() <= 0x400 || !starts_with(input, "yeelion-kuwo-tme")) {
        if (sniff_audio(input) == "aac") return Bytes(input.begin(), input.end());
        fail_invalid("不是支持的 KWM 文件");
    }
    std::uint64_t value = 0;
    for (std::size_t i = 0; i < 8; ++i) value |= std::uint64_t{input[0x18 + i]} << (i * 8);
    const std::string key_text = std::to_string(value);
    constexpr std::string_view predefined = "MoOtOiTvINGwd2E6n0E1i7L5t2IoOoNk";
    std::array<std::uint8_t, 32> mask{};
    for (std::size_t i = 0; i < 32; ++i) {
        mask[i] = static_cast<std::uint8_t>(predefined[i] ^ key_text[i % key_text.size()]);
    }
    Bytes audio(input.begin() + 0x400, input.end());
    for (std::size_t i = 0; i < audio.size(); ++i) audio[i] ^= mask[i % 32];
    return audio;
}

Bytes xiami(ByteSpan input) {
    if (input.size() < 16 || !starts_with(input, "ifmt") ||
        !std::all_of(input.begin() + 8, input.begin() + 12, [](std::uint8_t b) { return b == 0xfe; })) {
        fail_invalid("不是有效的 XM 文件");
    }
    const std::size_t start = std::size_t{input[12]} | std::size_t{input[13]} << 8 | std::size_t{input[14]} << 16;
    const std::uint8_t key = input[15];
    Bytes audio(input.begin() + 16, input.end());
    if (start > audio.size()) fail_invalid("XM 偏移无效");
    for (std::size_t i = start; i < audio.size(); ++i) audio[i] = static_cast<std::uint8_t>((audio[i] - key) ^ 0xff);
    return audio;
}

Bytes kugou(ByteSpan input, bool vpr, ByteSpan mask) {
    constexpr std::array<std::uint8_t, 16> vpr_header = {0x05, 0x28, 0xbc, 0x96, 0xe9, 0xe4, 0x5a, 0x43,
                                                         0x91, 0xaa, 0xbd, 0xd0, 0x7a, 0xf5, 0x36, 0x31};
    constexpr std::array<std::uint8_t, 16> kgm_header = {0x7c, 0xd5, 0x32, 0xeb, 0x86, 0x02, 0x7f, 0x4b,
                                                         0xa8, 0xaf, 0xa6, 0x8e, 0x0f, 0xff, 0x99, 0x14};
    if (input.size() < 0x2c || !starts_with(input, vpr ? vpr_header : kgm_header)) {
        fail_invalid("不是有效的 KGM/VPR 文件");
    }
    const std::size_t offset = u32le(input.subspan(0x10, 4));
    const std::uint32_t version = u32le(input.subspan(0x14, 4));
    if (version != 3) {
        fail_unsupported("此酷狗加密版本（" + std::to_string(version) + "）暂不支持；当前支持 KGM/VPR v3");
    }
    if (offset < 0x2c || offset >= input.size()) fail_invalid("KGM 音频偏移无效");
    Bytes audio(input.begin() + static_cast<std::ptrdiff_t>(offset), input.end());
    if (mask.empty() || (audio.size() + 15) / 16 > mask.size()) {
        fail_unsupported("KGM 掩码数据缺失或文件超出支持长度");
    }
    std::array<std::uint8_t, 17> key{};
    std::copy_n(input.begin() + 0x1c, 16, key.begin());
    constexpr std::array<std::uint8_t, 17> difference = {0x25, 0xdf, 0xe8, 0xa6, 0x75, 0x1e, 0x75, 0x0e, 0x2f,
                                                         0x80, 0xf3, 0x2d, 0xb8, 0xb6, 0xe3, 0x11, 0};
    for (std::size_t i = 0; i < audio.size(); ++i) {
        std::uint8_t value = key[i % 17] ^ audio[i];
        value ^= static_cast<std::uint8_t>((value & 15) << 4);
        std::uint8_t mask_byte = kgm_predefined[i % 272] ^ mask[i >> 4];
        mask_byte ^= static_cast<std::uint8_t>((mask_byte & 15) << 4);
        audio[i] = value ^ mask_byte ^ (vpr ? difference[i % 17] : 0);
    }
    return audio;
}

