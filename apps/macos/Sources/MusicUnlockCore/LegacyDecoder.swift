import Foundation

enum LegacyDecoder {
    static func decode(_ input: [UInt8], ext: String, kgmMask: Data?) throws -> [UInt8] {
        switch ext {
        case "uc": return input.map { $0 ^ 0xa3 }
        case "tm0", "tm3": return input
        case "tm2", "tm6":
            guard input.count >= 32, input[8..<12].allSatisfy({ $0 >= 0x20 && $0 <= 0x7e }) else {
                throw DecodeError.invalid("TM 文件未包含有效的 MP4 音频头部")
            }
            return [0, 0, 0, 0x20, 0x66, 0x74, 0x79, 0x70] + input.dropFirst(8)
        case "kwm": return try kuwo(input)
        case "xm": return try xiami(input)
        case "kgm", "kgma", "vpr": return try kugou(input, vpr: ext == "vpr", mask: kgmMask)
        default: throw DecodeError.unsupported("暂不支持 .\(ext)")
        }
    }

    private static func kuwo(_ input: [UInt8]) throws -> [UInt8] {
        guard input.count > 0x400, input.starts(with: Array("yeelion-kuwo-tme".utf8)) else {
            if AudioDecoder.sniff(input) == "aac" { return input }
            throw DecodeError.invalid("不是支持的 KWM 文件")
        }
        let value = input[0x18..<0x20].enumerated().reduce(UInt64(0)) { $0 | UInt64($1.element) << ($1.offset * 8) }
        let keyText = Array(String(value).utf8)
        let predefined = Array("MoOtOiTvINGwd2E6n0E1i7L5t2IoOoNk".utf8)
        let mask = (0..<32).map { predefined[$0] ^ keyText[$0 % keyText.count] }
        return input.dropFirst(0x400).enumerated().map { $0.element ^ mask[$0.offset % 32] }
    }

    private static func xiami(_ input: [UInt8]) throws -> [UInt8] {
        guard input.count >= 16, input.starts(with: Array("ifmt".utf8)),
              Array(input[8..<12]) == [0xfe, 0xfe, 0xfe, 0xfe] else {
            throw DecodeError.invalid("不是有效的 XM 文件")
        }
        let start = Int(input[12]) | Int(input[13]) << 8 | Int(input[14]) << 16
        let key = input[15]
        var audio = Array(input.dropFirst(16))
        guard start <= audio.count else { throw DecodeError.invalid("XM 偏移无效") }
        for i in start..<audio.count { audio[i] = (audio[i] &- key) ^ 0xff }
        return audio
    }

    private static func kugou(_ input: [UInt8], vpr: Bool, mask: Data?) throws -> [UInt8] {
        let header: [UInt8] = vpr
            ? [0x05,0x28,0xbc,0x96,0xe9,0xe4,0x5a,0x43,0x91,0xaa,0xbd,0xd0,0x7a,0xf5,0x36,0x31]
            : [0x7c,0xd5,0x32,0xeb,0x86,0x02,0x7f,0x4b,0xa8,0xaf,0xa6,0x8e,0x0f,0xff,0x99,0x14]
        guard input.count >= 0x2c, input.starts(with: header) else { throw DecodeError.invalid("不是有效的 KGM/VPR 文件") }
        let offset = Int(Array(input[0x10..<0x14]).uint32LE())
        let version = Array(input[0x14..<0x18]).uint32LE()
        guard version == 3 else {
            throw DecodeError.unsupported("此酷狗加密版本（\(version)）暂不支持；当前支持 KGM/VPR v3")
        }
        guard offset >= 0x2c, offset < input.count else { throw DecodeError.invalid("KGM 音频偏移无效") }
        var audio = Array(input.dropFirst(offset))
        guard let mask, (audio.count + 15) / 16 <= mask.count else {
            throw DecodeError.unsupported("KGM 掩码数据缺失或文件超出支持长度")
        }
        let table = [UInt8](mask)
        let key = Array(input[0x1c..<0x2c]) + [0]
        let difference: [UInt8] = [0x25,0xdf,0xe8,0xa6,0x75,0x1e,0x75,0x0e,0x2f,0x80,0xf3,0x2d,0xb8,0xb6,0xe3,0x11,0]
        for i in audio.indices {
            var value = key[i % 17] ^ audio[i]
            value ^= (value & 15) << 4
            var maskByte = kgmPredefined[i % 272] ^ table[i >> 4]
            maskByte ^= (maskByte & 15) << 4
            audio[i] = value ^ maskByte ^ (vpr ? difference[i % 17] : 0)
        }
        return audio
    }

